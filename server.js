function hashLicenseKey(key) {
  return crypto.createHash('sha256').update(String(key)).digest('hex');
}

/* ------------------------------------------------------------------ *
 * 1. LICENSE VERIFICATION (SOHAM.LICENSE) -- with zero-config fallback
 * ------------------------------------------------------------------ *
 * If you set LICENSE_KEY + LICENSE_KEY_HASH yourself (recommended for
 * a real deployment), those are used and must match. If you don't set
 * them at all, the server generates a one-off pair automatically so
 * it still boots -- convenient for a quick first deploy, but note:
 * that generated key only lives in this process's memory, so it is
 * NOT a real access-control key and won't survive a restart. Set your
 * own via `node scripts/generate-license-hash.js` before going live.
 * ------------------------------------------------------------------ */

let licenseAutoGenerated = false;
if (!process.env.LICENSE_KEY || !process.env.LICENSE_KEY_HASH) {
  const autoKey = crypto.randomBytes(24).toString('hex');
  process.env.LICENSE_KEY = autoKey;
  process.env.LICENSE_KEY_HASH = hashLicenseKey(autoKey);
  licenseAutoGenerated = true;
  console.log('[SOHAM.LICENSE] LICENSE_KEY / LICENSE_KEY_HASH not set -- auto-generated one for this session only.');
  console.log('[SOHAM.LICENSE] Set your own permanent pair before real deployment: npm run generate:license-hash');
}

function verifyLicense() {
  const suppliedHash = hashLicenseKey(process.env.LICENSE_KEY);
  const expectedHash = process.env.LICENSE_KEY_HASH;
  const a = Buffer.from(suppliedHash, 'hex');
  const b = Buffer.from(expectedHash, 'hex');
  const valid = a.length === b.length && crypto.timingSafeEqual(a, b);
  return valid ? { valid: true } : { valid: false, reason: 'LICENSE_KEY does not match LICENSE_KEY_HASH.' };
}

const licenseStatus = verifyLicense();

if (licenseStatus.valid) {
  console.log('[SOHAM.LICENSE] License verified. Starting server normally.');
} else {
  console.error(`[SOHAM.LICENSE] License check FAILED: ${licenseStatus.reason}`);
}

app.use((req, res, next) => {
  if (licenseStatus.valid) return next();
  res.status(503).type('html').send(`
    <!doctype html>
    <html><head><meta charset="utf-8"><title>License Invalid</title></head>
    <body style="font-family: sans-serif; max-width: 640px; margin: 80px auto; color:#2B2418;">
      <h1>Service unavailable</h1>
      <p>This deployment's license key could not be verified.</p>
      <p style="color:#888; font-size: 13px;">Reason: ${licenseStatus.reason}</p>
    </body></html>
  `);
});

